  const RAW = [KITCHEN, LAPTOP, MONEY];

  function isoAgo(hours, now) {
    return new Date(now - hours * 3600000).toISOString();
  }

  function buildDemo(key, now) {
    const base = now === undefined ? Date.now() : now;
    const raw = RAW.find(d => d.key === key) || RAW[0];
    const video = {
      id: 'demo-' + raw.key,
      title: raw.title,
      channelTitle: raw.channelTitle,
      channelId: 'demo-channel-' + raw.key,
      description: '데모 데이터 · 실제 유튜브 영상이 아닙니다',
      publishedAt: isoAgo(raw.publishedDaysAgo * 24, base),
      viewCount: raw.viewCount,
      likeCount: raw.likeCount,
      commentCount: raw.comments.length,
      thumbnail: '',
      source: 'demo',
    };
    const comments = raw.comments.map((row, i) => ({
      id: 'demo-' + raw.key + '-' + String(i + 1).padStart(2, '0'),
      author: row[0],
      text: row[1],
      likeCount: row[2],
      replyCount: row[3],
      publishedAt: isoAgo(row[4], base),
      source: 'demo',
    }));
    return { video, comments, demo: { key: raw.key, label: raw.label, kind: raw.kind, accent: raw.accent, accent2: raw.accent2, hook: raw.hook } };
  }

  function listDemos() {
    return RAW.map(d => ({
      key: d.key, label: d.label, kind: d.kind, title: d.title,
      channelTitle: d.channelTitle, count: d.comments.length,
      viewCount: d.viewCount, accent: d.accent, accent2: d.accent2, hook: d.hook,
      publishedDaysAgo: d.publishedDaysAgo,
    }));
  }

  return { RAW, buildDemo, listDemos };
